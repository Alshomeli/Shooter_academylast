export function publicText(value: string | undefined, lang: Lang, english?: string): string {
  if (!value) return '';
  if (lang === 'ar') return value;
  return english?.trim() || publicEnglish[value] || value;
}

export function publicLanguage(search: string, saved: Lang): Lang {
  const asked = new URLSearchParams(search).get('lang');
  return asked === 'ar' || asked === 'en' ? asked : saved;
}
